class Texts:
    """Texts in the language Home Assistant is set to (read on every use, so a change applies at once)."""

    def __init__(self, hass: HomeAssistant) -> None:
        self.hass = hass

    def _table(self) -> dict[str, str]:
        language = (self.hass.config.language or "en").split("-")[0].lower()
        return TEXTS.get(language, TEXTS["en"])

    def __call__(self, key: str, **values: Any) -> str:
        text = self._table().get(key) or TEXTS["en"][key]
        return text.format(**values) if values else text

    def n(self, key: str, count: int, **values: Any) -> str:
        """Singular or plural form: key_one for exactly one, key_other otherwise."""
        return self(f"{key}_{'one' if count == 1 else 'other'}", count=count, **values)

    def reason(self, code: Any, prefix: str = "") -> str:
        """Text for a reason code from the PC; an unknown code is shown as it is. prefix: a text of
        its own for some codes first (<prefix>reason_<code>, e.g. move_ for a move)."""
        text = str(code or "")
        for key in (f"{prefix}reason_{text}", f"reason_{text}") if prefix else (f"reason_{text}",):
            if key in TEXTS["en"]:
                return self(key)
        return text

    def date(self, iso_date: str) -> str:
        """YYYY-MM-DD as the language writes it."""
        year, month, day = iso_date[0:4], iso_date[5:7], iso_date[8:10]
        return f"{day}.{month}.{year}" if self._table() is TEXTS["de"] else f"{year}-{month}-{day}"
